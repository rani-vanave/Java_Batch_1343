package loops_in_java;

public class Multiplication_tables1to10 {
	 public static void main(String[] args) {
	        for (int n = 1; n <= 10; n++) {
	            for (int i = 1; i <= 10; i++) {
	                System.out.print(n * i + "\t");
	            }
	            System.out.println();
	        }
	    }
	}

