package operator;

public class Relational1 {
	public static void main(String[] args) {
		int a = 10, b = 5;
		System.out.println(a > b);
	
	  int x = 7, y = 12;
	  System.out.println(x < y);
	  
	  int p = 8, q = 8;
	  System.out.println(p == q);
	  
	  int m = 15, n = 9;
	  System.out.println(m != n);
	
	  System.out.println(a <= b);
	
	  System.out.println(m >= n);
	  System.out.println(x != y);
	
	  System.out.println(p < q);
	  System.out.println(x <= y);
	  System.out.println(m != n);
	
	
	
	
	
	}
	}
