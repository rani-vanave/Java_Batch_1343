package operator;

public class RelationalOperator3 {
public static void main(String[] args) {
	int a = 10, b = 5, c = 10;

    System.out.println(a > b);   // 1
    System.out.println(a < b);   // 2
    System.out.println(a == c);  // 3
    System.out.println(a != c);  // 4
    System.out.println(a >= c);  // 5
    System.out.println(a <= c);  // 6
    System.out.println(b < c);   // 7
    System.out.println(b > c);   // 8
    System.out.println(b != c);  // 9
    System.out.println(b == c);  // 10
    System.out.println(c >= a);  // 11
    System.out.println(c <= a);  // 12
    System.out.println(a >= b);  // 13
    System.out.println(a <= b);  // 14
    System.out.println(b >= a);  // 15
    System.out.println(b <= a);  // 16
    System.out.println(c > b);   // 17
    System.out.println(c < b);   // 18
    System.out.println(a != b);  // 19
    System.out.println(c == b);  // 20
	
}
}

