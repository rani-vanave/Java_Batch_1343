package swtich_case;

public class Color_name {
	public static void main(String[] args) {
		String color="Green";
		
		switch(color) {
		case "red":
			System.out.println("stop");
			break;
			
		case "yellow":
			System.out.println("ready");
			break;
			
		case "Green":
			System.out.println("Go");
			break;
			
		}
	}

}
